package com.neep.neepmeat.api.live_machine;

import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.EntityBlock;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityTicker;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import org.jetbrains.annotations.Nullable;

public abstract class LivingMachineBlock extends Block implements EntityBlock
{
    public LivingMachineBlock(Properties settings)
    {
        super(settings);
    }

    @Nullable
    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level world, BlockState state, BlockEntityType<T> type)
    {
        return !world.isClientSide() ? (world1, pos, state1, blockEntity) ->
        {
            if (blockEntity instanceof LivingMachineBlockEntity be)
            {
                be.serverTick();
            }
        } : null;
    }
//    protected abstract <T extends LivingMachineBlockEntity> T makeBlockEntity(BlockPos pos, BlockState state);
}
