package com.neep.neepmeat.machine.live_machine.block.entity;

import com.neep.meatlib.transfer.FluidVariant;
import com.neep.meatlib.transfer.Storage;
import com.neep.neepmeat.api.live_machine.ComponentType;
import com.neep.neepmeat.api.live_machine.LivingMachineComponent;
import com.neep.neepmeat.api.storage.WritableSingleFluidStorage;
import com.neep.neepmeat.machine.live_machine.LivingMachineComponents;
import com.neep.neepmeat.machine.live_machine.LivingMachines;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.state.BlockState;

/** Work-fluid buffer. The repair charge item is not applied yet. */
public class IntegrationPortBlockEntity extends BlockEntity implements LivingMachineComponent {
    private final WritableSingleFluidStorage storage = new WritableSingleFluidStorage(8 * 81000L, this::setChanged);

    public IntegrationPortBlockEntity(BlockPos pos, BlockState state) {
        super(LivingMachines.INTEGRATION_BE.get(), pos, state);
    }

    public Storage<FluidVariant> getFluidStorage(Direction side) {
        return storage;
    }

    @Override
    public boolean componentRemoved() {
        return isRemoved();
    }

    @Override
    public ComponentType<? extends LivingMachineComponent> getComponentType() {
        return LivingMachineComponents.INTEGRATION_PORT;
    }
}
