public class FilteredEjectorBlock extends EjectorBlock
{
    public FilteredEjectorBlock(RegistrationContext ctx, ItemSettings itemSettings, FabricBlockSettings settings)
    {
        super(ctx, itemSettings, settings);
    }

    @Override
    protected InteractionResult useWithoutItem(BlockState state, Level world, BlockPos pos, Player player, BlockHitResult hit)
    {
        if (world.getBlockEntity(pos) instanceof FilteredEjectorBlockEntity be)
        {
            if (player.isShiftKeyDown() && player.getMainHandItem().isEmpty())
            {
                be.changeMode();
                world.playSound(null, pos, MeatlibSounds.CLICK, SoundSource.BLOCKS, 1, 1);
            }
            else
            {
                player.openMenu(be);
            }
            return InteractionResult.SUCCESS;
        }
        return super.useWithoutItem(state, world, pos, player, hit);
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state)
    {
        return ItemTransport.FILTERED_EJECTOR_BE.create(pos, state);
    }

    @Nullable
    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level world, BlockState state, BlockEntityType<T> type)
    {
        return MiscUtil.checkType(type, ItemTransport.FILTERED_EJECTOR_BE, (world1, pos, state1, blockEntity) -> ((FilteredEjectorBlockEntity) blockEntity).serverTick(), null, world);
    }
}
