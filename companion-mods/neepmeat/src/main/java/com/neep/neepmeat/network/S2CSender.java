package com.neep.neepmeat.network;

import net.fabricmc.fabric.api.networking.v1.PacketByteBufs;
import net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking;
import net.minecraft.network.FriendlyByteBuf;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.player.Player;

public interface S2CSender
{
    static FriendlyByteBuf getBuf()
    {
        return PacketByteBufs.create();
    }

    static void send(Player player, ResourceLocation identifier, FriendlyByteBuf buf)
    {
        ServerPlayNetworking.send((ServerPlayer) player, identifier, buf);
    }
}
